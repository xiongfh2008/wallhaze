/**
 * Generate responsive WebP derivatives for homepage-critical artwork.
 *
 * Convention: for a source file `/images/<dir>/<name>.<ext>` the script
 * writes `/images/<dir>/<name>-<WIDTH>.webp` next to it, never wider than
 * the original. Originals stay untouched — they remain the download assets
 * and the last-resort <img src>. Card components opt into the variants via
 * lib/images.ts; anything not generated here simply has no srcset entry.
 *
 * Run: node scripts/media/build-derivatives.mjs
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..", "..", "public", "images");

/** Widths per directory. The original width is always the cap. */
const PLAN = {
  wallpapers: {
    widths: [640, 960, 1280, 1920],
    quality: 80,
    /** Wallpaper originals are download assets — derive from JPG/PNG only. */
    sourcePattern: /\.(jpe?g|png)$/i,
  },
  styles: {
    widths: [480],
    quality: 80,
    /** Style previews include WebP originals (project-generated). */
    sourcePattern: /\.(jpe?g|png|webp)$/i,
  },
};

/** src → { widths: available WebP variant widths, natural: source width }. */
const MANIFEST = {};
const SUMMARY = [];

for (const [dir, { widths, quality, sourcePattern }] of Object.entries(PLAN)) {
  const sourceDir = path.join(ROOT, dir);
  await mkdir(sourceDir, { recursive: true });
  for (const entry of await readdir(sourceDir)) {
    if (!sourcePattern.test(entry) || /-\d+\.webp$/i.test(entry)) continue;
    const base = entry.replace(/\.(jpe?g|png|webp)$/i, "");
    const source = path.join(sourceDir, entry);
    const meta = await sharp(source).metadata();
    const available = [];
    for (const width of widths) {
      // Only skip widths that would UPSCALE; same-width re-encodes are the
      // point (a 1920 WebP of a 1920 JPEG costs ~1/4 of the bytes).
      if (width > meta.width) continue;
      const target = path.join(sourceDir, `${base}-${width}.webp`);
      const buffer = await sharp(source)
        .resize({ width, withoutEnlargement: true })
        .webp({ quality })
        .toBuffer();
      await writeFile(target, buffer);
      available.push(width);
      SUMMARY.push({
        file: `${dir}/${base}-${width}.webp`,
        kb: Math.round(buffer.length / 1024),
        from: `${meta.width}x${meta.height}`,
      });
    }
    MANIFEST[`/images/${dir}/${entry}`] = {
      widths: available,
      natural: meta.width,
    };
  }
}

// Generated manifest consumed by lib/images.ts — keeps srcset entries in
// exact sync with the files on disk (a missing candidate would 404).
const manifestPath = path.resolve(
  import.meta.dirname,
  "..",
  "..",
  "lib",
  "image-variants.generated.ts"
);
const manifestBody = `/* eslint-disable */
/**
 * GENERATED by scripts/media/build-derivatives.mjs — do not edit by hand.
 * Maps each optimizable source image to its generated WebP variant widths
 * plus the natural (source) pixel width. See lib/images.ts for consumption.
 */
export interface ImageVariantEntry {
  /** Generated -<WIDTH>.webp widths. */
  widths: number[];
  /** Natural source width (used as the widest srcset candidate). */
  natural: number;
}

export const IMAGE_VARIANTS: Record<string, ImageVariantEntry> = ${JSON.stringify(
  MANIFEST,
  null,
  2
)};
`;
await writeFile(manifestPath, manifestBody);

let saved = 0;
for (const row of SUMMARY) {
  console.log(`${row.file}  ${row.kb}KB  (source ${row.from})`);
  saved += row.kb;
}
console.log(
  `${SUMMARY.length} derivatives, ${Math.round(saved / 1024)} MB total, manifest entries ${Object.keys(MANIFEST).length}`
);
